    <script>
        loadServices();
        loadProjects();

        function loadServices() {

            fetch('/decorluxe/business/admin/settings/get_services.php')

                .then(res => res.text())
                .then(html => {
                    document.getElementById("servicesContainer").innerHTML = html;
                });

        }


        function loadProjects() {

            fetch('/decorluxe/business/admin/settings/get_projects.php')

                .then(res => res.text())
                .then(html => {
                    document.getElementById("projectsContainer").innerHTML = html;
                });

        }

        function saveHomepageSettings() {

            let form = new FormData();

            document
                .querySelectorAll("input[name='services[]']:checked")
                .forEach(el => {

                    form.append("services[]", el.value)

                });


            document
                .querySelectorAll("input[name='projects[]']:checked")
                .forEach(el => {

                    form.append("projects[]", el.value)

                });


            document
                .querySelectorAll("textarea[name^='project_desc']")
                .forEach(el => {

                    form.append(el.name, el.value)

                });


            fetch('/decorluxe/business/admin/settings/save_homepage.php', {
                    method: 'POST',
                    body: form
                })
                .then(res => res.text())
                .then(() => {
                    alert("Settings Saved");
                });

        }
    </script>